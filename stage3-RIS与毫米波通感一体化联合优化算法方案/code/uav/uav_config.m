function cfg=uav_config(profile)
% A deployment experiment: hover during both CPIs, stationary ground targets.
if nargin<1, profile='full'; end
cfg=struct('profile',profile,'mc',300,'rcs_m2',[1 10 100], ...
    'seed',20261116,'power_w',1,'temperature_k',290,'noise_figure_db',7, ...
    'reference_range_m',200,'hover',[0 0 80],'ris',[260 60 25], ...
    'ris_normal',[-1 0 0],'users',[70 -50 0;90 50 0], ...
    'targets',[180 -25 0;220 35 0],'target_jitter_m',8,'prior_sigma_m',10, ...
    'methods',{{'Fixed_NoRIS','Fixed_RIS','Selected_NoRIS','Selected_RIS'}}, ...
    'failure_position_m',5,'primary_rcs_m2',10,'bootstrap_seed',20261117);
[x,y]=ndgrid([-40 0 40]); cfg.candidates=[x(:),y(:),80*ones(numel(x),1)];
if strcmp(profile,'smoke')
    cfg.mc=1; cfg.rcs_m2=[1000 10000 100000]; % Exercise fine-estimation branches with a small smoke grid.
elseif ~ismember(profile,{'full','pilot'})
    error('Unknown profile: %s',profile);
end
end
